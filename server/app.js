require('dotenv').config();
const express = require('express'); const cors = require('cors'); const cookieParser = require('cookie-parser'); const helmet = require('helmet');
const { requireCsrfToken } = require('./middleware/csrf.middleware');
const app = express();
app.use(helmet());
app.use(cors({ origin: process.env.FRONTEND_URL || 'http://localhost:5173', credentials: true }));
app.use(express.json({ limit: '1mb' })); app.use(express.urlencoded({ extended: true, limit: '1mb' })); app.use(cookieParser()); app.use(requireCsrfToken);
app.get('/api/health', (_req, res) => res.json({ success: true, message: 'CampusFlow API is running.' }));
app.use('/api/auth', require('./routes/auth.routes'));
app.use('/api/users', require('./routes/user.routes'));
app.use('/api/requests', require('./routes/request.routes'));
app.use('/api/approvals', require('./routes/approval.routes'));
app.use((req, res) => res.status(404).json({ success: false, message: `Route ${req.originalUrl} not found.` }));
app.use(require('./utils/errorHandler'));
module.exports = app;
